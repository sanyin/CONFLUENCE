export const DEFAULT_ROSTER = ['conductor', 'scout', 'builder', 'critic', 'weaver'];

export function personaByKey(key) {
  return PERSONAS.find((p) => p.key === key) || null;
}

export function agentSystemPrompt(agent) {
  const persona = personaByKey(agent.personaKey);
  const head = persona
    ? `你是 ${agent.name}（${agent.role}）。${persona.desc}\n${persona.system}`
    : `你是 ${agent.name}（${agent.role}）。${agent.system || ''}`;
  return `${head}\n\n${PROTOCOL}`;
}
